#!/usr/bin/env python3
"""Regenerate test/ota_vectors.h for the ak_ota host tests.

Uses a throwaway key that exists only while this script runs; only the public
key and the signed headers are written. Run: python3 test/gen_ota_vectors.py
"""

import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "tools"))
import ota_pack  # noqa: E402

from cryptography.hazmat.primitives.asymmetric import ec  # noqa: E402


def c_array(name: str, data: bytes) -> str:
    rows = "\n".join("    " + " ".join(f"0x{b:02x}," for b in data[i:i + 16])
                     for i in range(0, len(data), 16))
    return f"static const uint8_t {name}[{len(data)}] = {{\n{rows}\n}};\n"


def main() -> int:
    key = ec.generate_private_key(ec.SECP256R1())
    other = ec.generate_private_key(ec.SECP256R1())
    body = bytes((i * 7 + 3) & 0xFF for i in range(700))  # 64 + 700 = 3 chunks
    ug = struct.pack("<16I", ota_pack.UG_MAGIC, ota_pack.UG_TYPE_LZMA_FULL, 1, 1,
                     4096, 4096, 64, 0, len(body), 0, 0, 0x1000, 0x20000, 0, 0, 0) + body
    rel = ota_pack.sign_package(ug, (0, 3, 60), ota_pack.PROFILE_RELEASE, key)
    dbg = ota_pack.sign_package(ug, (0, 3, 60), ota_pack.PROFILE_DEBUG, key)
    foreign = ota_pack.sign_package(ug, (0, 3, 60), ota_pack.PROFILE_RELEASE, other)
    out = ["/* Generated by test/gen_ota_vectors.py; do not edit. */",
           "#ifndef OTA_VECTORS_H", "#define OTA_VECTORS_H", "#include <stdint.h>", "",
           c_array("ota_vec_point", ota_pack.point_bytes(key.public_key())),
           c_array("ota_vec_header_release", rel[:ota_pack.HEADER_LEN]),
           c_array("ota_vec_header_debug", dbg[:ota_pack.HEADER_LEN]),
           c_array("ota_vec_header_foreign", foreign[:ota_pack.HEADER_LEN]),
           c_array("ota_vec_image", ug), "#endif", ""]
    (HERE / "ota_vectors.h").write_text("\n".join(out), encoding="utf-8")
    print("wrote", HERE / "ota_vectors.h")
    return 0


if __name__ == "__main__":
    sys.exit(main())
