#!/usr/bin/env python3
"""Generate common/src/ak_font_data.c: the subset fonts for the on-device font test.

Needs Pillow, numpy and fontTools, plus the source fonts (not stored in the repo,
see third_party/fonts/THIRD_PARTY.md for where to get them and their licences):

  python3 tools/gen_font_data.py \
      --fusion fusion-pixel-12px-monospaced-zh_hans.ttf \
      --unifont unifont-18.0.01.otf \
      --chill ChillBitmap_16px.ttf \
      --isas gb16st.bdf

The glyph set is ASCII 0x20..0x7E plus every character in tools/font_sample.txt,
so the data stays a few tens of KB. The sample lines are emitted into the same
file, which keeps what the board shows and what the font contains in sync.
Glyphs are loaded by tools/ak_fontsrc.py, the same loader the review previews use.
"""
import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ak_fontsrc import Merged, TtfFace, glyph_or_box, load_bdf  # noqa: E402

OUT = os.path.join(HERE, "..", "common", "src", "ak_font_data.c")
SAMPLE = os.path.join(HERE, "font_sample.txt")

MISSING = 0x7F


def pack(levels, bpp):
    """levels: 2-D uint8, row-major, MSB first, glyph padded to whole bytes."""
    bits = np.unpackbits(levels.reshape(-1, 1).astype(np.uint8), axis=1)[:, 8 - bpp:].reshape(-1)
    bits = np.concatenate([bits, np.zeros((-len(bits)) % 8, np.uint8)])
    return np.packbits(bits).tobytes()


def build(face, label, chars):
    entries = {}
    for ch in sorted(set(chars) | {chr(MISSING)}):
        cp = ord(ch)
        # 0x7F is never a real glyph here: it is the engine's missing-glyph box.
        src = None if cp == MISSING else face
        if src is not None and not face.has(cp):
            raise SystemExit("%s lacks U+%04X %r" % (face.name, cp, ch))
        adv, levels = glyph_or_box(face, -1 if cp == MISSING else cp, max(4, face.h // 2))
        entries[cp] = (adv, pack(levels, face.bpp))
    codes = sorted(entries)
    data, offs, adv = bytearray(), [], []
    for cp in codes:
        offs.append(len(data))
        adv.append(entries[cp][0])
        data += entries[cp][1]
    return dict(name=label, px=face.h, bpp=face.bpp, line=face.h + 2, codes=codes, adv=adv, offs=offs,
                data=bytes(data))


def c_bytes(b, per=16):
    return ",\n".join("    " + ", ".join("0x%02X" % x for x in b[i:i + per]) for i in range(0, len(b), per))


def c_str(s):
    """UTF-8 as octal escapes (a following hex digit can never extend one)."""
    return "".join(chr(b) if 0x20 <= b < 0x7F and chr(b) not in '"\\?' else "\\%03o" % b for b in s.encode("utf-8"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fusion", required=True, help="fusion-pixel-12px-monospaced-zh_hans.ttf")
    ap.add_argument("--unifont", required=True, help="unifont-18.0.01.otf")
    ap.add_argument("--chill", required=True, help="ChillBitmap_16px.ttf")
    ap.add_argument("--isas", required=True, help="gb16st.bdf from X.Org font-isas-misc")
    a = ap.parse_args()

    lines = [l.rstrip("\n") for l in open(SAMPLE, encoding="utf-8") if l.strip()]
    chars = [chr(c) for c in range(0x20, 0x7F)] + [c for l in lines for c in l]

    unifont = TtfFace(a.unifont, 16, 14, 16, "unifont", 1, cjk_adv=16)
    faces = [
        ("ak_font_fusion12", "Fusion Pixel 12px",
         TtfFace(a.fusion, 12, 10, 12, "fusion", 1, cjk_adv=12)),
        ("ak_font_unifont16", "GNU Unifont 16px", unifont),
        ("ak_font_chill16", "Unifont 16px alt Latin",
         TtfFace(a.chill, 16, 14, 17, "chill", 1, cjk_adv=16)),
        ("ak_font_isas16", "ISAS Song 16px",
         Merged("isas+unifont", load_bdf(a.isas, 14, 16, "isas", gb2312=True), unifont)),
    ]
    fonts = [(sym, build(face, label, chars)) for sym, label, face in faces]

    o = []
    o.append("/* GENERATED by tools/gen_font_data.py -- do not edit by hand.\n"
             " * Subset bitmaps (ASCII + font_sample.txt) taken from:\n"
             " *   Fusion Pixel Font 2026.11.10 (SIL OFL 1.1) -- (c) 2022 TakWolf\n"
             " *   GNU Unifont 18.0.01 (SIL OFL 1.1) -- (c) 1998-2026 Roman Czyborra, Paul Hardy, Qianqian Fang et al.\n"
             " *   Chill Bitmap 16px v2.502 (SIL OFL 1.1, Unifont-based) -- Warren2060 / Unifont authors\n"
             " *   ISAS gb16st (X.Org font-isas-misc 1.0.4) -- (c) 1988 The Institute of Software, Academia Sinica\n"
             " * See firmware/app/third_party/fonts/THIRD_PARTY.md. */\n")
    o.append('#include "ak_font_data.h"\n')
    for sym, f in fonts:
        o.append("static const uint16_t %s_codes[%d] = {\n%s\n};" % (
            sym, len(f["codes"]), ",\n".join(
                "    " + ", ".join("0x%04X" % x for x in f["codes"][i:i + 8]) for i in range(0, len(f["codes"]), 8))))
        o.append("static const uint8_t %s_adv[%d] = {\n%s\n};" % (sym, len(f["adv"]), c_bytes(bytes(f["adv"]))))
        o.append("static const uint32_t %s_offs[%d] = {\n%s\n};" % (sym, len(f["offs"]), ",\n".join(
            "    " + ", ".join("%d" % x for x in f["offs"][i:i + 8]) for i in range(0, len(f["offs"]), 8))))
        o.append("static const uint8_t %s_data[%d] = {\n%s\n};" % (sym, len(f["data"]), c_bytes(f["data"])))
        o.append("static const ak_font_t %s = {\n    \"%s\", %d, %d, %d, %d,\n    %s_codes, %s_adv, %s_offs, %s_data,\n};\n" % (
            sym, f["name"], f["px"], f["bpp"], f["line"], len(f["codes"]), sym, sym, sym, sym))
    o.append("const ak_font_t *const ak_font_test_set[AK_FONT_TEST_COUNT] = {\n%s\n};\n" % ",\n".join(
        "    &" + s for s, _ in fonts))
    o.append("const char *const ak_font_sample[AK_FONT_SAMPLE_LINES] = {\n%s\n};\n" % ",\n".join(
        '    "%s" /* %s */' % (c_str(l), l.replace("*/", "* /")) for l in lines))
    assert len(fonts) == 4, "AK_FONT_TEST_COUNT in ak_font_data.h must match"
    assert len(lines) == 5, "AK_FONT_SAMPLE_LINES in ak_font_data.h must match the sample file"
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(o))
    for sym, f in fonts:
        print(sym, "glyphs", len(f["codes"]), "bytes", len(f["data"]))


if __name__ == "__main__":
    main()
